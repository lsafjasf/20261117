/**
 * Mesh assembly: combines lathed body + handle into one indexed mesh,
 * exposes draggable profile control points (z=0 edit plane) and OBJ export.
 */
(function (global) {
  'use strict';
  var NS = (global.TeaCup = global.TeaCup || {});
  var geom = NS.geometry;
  var handleMod = NS.handle;

  function buildMesh(params) {
    var profile = geom.buildProfile(params);
    var body = geom.lathe(profile, params.segments, 'body');
    var handle = handleMod.buildHandle(params);
    var offset = body.vertices.length;
    var vertices = body.vertices.concat(handle.vertices);
    var faces = body.faces.concat(handle.faces.map(function (f) {
      return { indices: f.indices.map(function (i) { return i + offset; }),
        group: f.group };
    }));
    var bbox = boundingBox(vertices);
    return {
      params: params,
      profile: profile,
      vertices: vertices,
      faces: faces,
      handle: handle,
      bbox: bbox,
      controlPoints: buildControlPoints(params)
    };
  }

  function buildControlPoints(p) {
    var H = p.height;
    return [
      { id: 'rim', label: '杯口', field: 'rimRadius',
        position: [p.rimRadius, H, 0], axis: 'x',
        min: NS.params.LIMITS.rimRadius.min,
        max: NS.params.LIMITS.rimRadius.max },
      { id: 'waist', label: '腰身', field: 'waistRadius',
        position: [p.waistRadius, 0.1 * H + 0.45 * 0.9 * H, 0], axis: 'x',
        min: NS.params.LIMITS.waistRadius.min,
        max: NS.params.LIMITS.waistRadius.max },
      { id: 'base', label: '底足', field: 'baseRadius',
        position: [p.baseRadius, 0.07 * H, 0], axis: 'x',
        min: NS.params.LIMITS.baseRadius.min,
        max: NS.params.LIMITS.baseRadius.max },
      { id: 'height', label: '杯高', field: 'height',
        position: [p.rimRadius, H, 0], axis: 'y',
        min: NS.params.LIMITS.height.min,
        max: NS.params.LIMITS.height.max },
      { id: 'reach', label: '把手外伸', field: 'handleReach',
        position: [p.rimRadius * 0.96 - 0.06 + p.handleReach,
          0.72 * H + 0.18 * H, 0], axis: 'x',
        min: NS.params.LIMITS.handleReach.min,
        max: NS.params.LIMITS.handleReach.max }
    ];
  }

  function boundingBox(vertices) {
    var min = [Infinity, Infinity, Infinity];
    var max = [-Infinity, -Infinity, -Infinity];
    vertices.forEach(function (v) {
      for (var i = 0; i < 3; i++) {
        if (v[i] < min[i]) min[i] = v[i];
        if (v[i] > max[i]) max[i] = v[i];
      }
    });
    var center = [
      (min[0] + max[0]) / 2, (min[1] + max[1]) / 2,
      (min[2] + max[2]) / 2
    ];
    var size = [max[0] - min[0], max[1] - min[1], max[2] - min[2]];
    return { min: min, max: max, center: center, size: size };
  }

  /**
   * Wavefront OBJ. One file, two groups; faces are 1-based.
   * Group order is fixed: body first, handle second (layer ordering contract).
   */
  function toOBJ(mesh) {
    var lines = ['# Procedural low-poly teacup - generated by TeaCup app'];
    lines.push('o teacup');
    mesh.vertices.forEach(function (v) {
      lines.push('v ' + v[0].toFixed(6) + ' ' + v[1].toFixed(6) +
        ' ' + v[2].toFixed(6));
    });
    lines.push('g body');
    mesh.faces.forEach(function (f) {
      if (f.group !== 'body') return;
      lines.push('f ' + f.indices.map(function (i) { return i + 1; }).join(' '));
    });
    lines.push('g handle');
    mesh.faces.forEach(function (f) {
      if (f.group !== 'handle') return;
      lines.push('f ' + f.indices.map(function (i) { return i + 1; }).join(' '));
    });
    return lines.join('\n') + '\n';
  }

  NS.mesh = { buildMesh: buildMesh, boundingBox: boundingBox, toOBJ: toOBJ };
})(typeof globalThis !== 'undefined' ? globalThis : this);
