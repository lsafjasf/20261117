// Compact 5x7 bitmap font covering the HUD alphabet (digits, letters and a
// few symbols). Each glyph is seven rows of five bits, MSB on the left.

const GLYPHS = {
  '0': [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
  '1': [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
  '2': [0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F],
  '3': [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
  '4': [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
  '5': [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
  '6': [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
  '7': [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
  '8': [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
  '9': [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
  t: [0x08, 0x08, 0x1C, 0x08, 0x08, 0x09, 0x06],
  m: [0x00, 0x19, 0x1A, 0x16, 0x16, 0x16, 0x16],
  s: [0x00, 0x0E, 0x10, 0x0E, 0x01, 0x01, 0x1E],
  '-': [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
  '=': [0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00, 0x00],
  ' ': [0, 0, 0, 0, 0, 0, 0]
};

export function drawText(pixels, width, height, text, x, y, color, scale = 1) {
  let cursorX = Math.round(x);
  const baselineY = Math.round(y) - 7 * scale;
  for (const char of String(text)) {
    const glyph = GLYPHS[char] || GLYPHS[' '];
    glyph.forEach((row, rowIndex) => {
      for (let column = 0; column < 5; column += 1) {
        if (!(row & (1 << (4 - column)))) continue;
        for (let dy = 0; dy < scale; dy += 1) {
          for (let dx = 0; dx < scale; dx += 1) {
            const px = cursorX + column * scale + dx;
            const py = baselineY + rowIndex * scale + dy;
            if (px >= 0 && px < width && py >= 0 && py < height) {
              pixels[py * width + px] = { ...color };
            }
          }
        }
      }
    });
    cursorX += 6 * scale;
  }
}
